const lookup = (dictionary, key) => key.split('.').reduce((value, part) => (value == null ? undefined : value[part]), dictionary);

export function createPartyT(language = 'fr') {
    const dictionary = strings[language] || strings.fr;
    return (key, vars = {}) => {
        const value = lookup(dictionary, key) ?? lookup(strings.fr, key);
        if (typeof value !== 'string') return key;
        return value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? vars[name] : match));
    };
}
